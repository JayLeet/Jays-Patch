Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$PatchRoot = Join-Path $RepoRoot "Jays-Patch"
$ConfigPath = Join-Path $PatchRoot "role-icons.json"
$OutputPath = Join-Path $PatchRoot "datapack/data/botc_patch/function/setup/clear_known_roles.mcfunction"
$ContractPath = Join-Path $PatchRoot "upstream-contract.json"
$RoleExtensionPath = Join-Path $PatchRoot "role-extensions.json"
$SetFromMenuPath = Join-Path $RepoRoot "data/resources/datapack/required/ct/data/ct/function/admin/setup/set_from_menu.mcfunction"
$CharactersPath = Join-Path $RepoRoot "data/resources/datapack/required/ct/data/ct/function/admin/setup/characters.mcfunction"
$RoleCatalogHelper = Join-Path $RepoRoot "tools/lib/sybillian-role-catalog.ps1"
$CompatibilityRoot = Join-Path $PatchRoot "datapack/data/botc_patch/function/setup/compatibility"
$ImportValidationPath = Join-Path $PatchRoot "datapack/data/botc_patch/function/setup/import/validate_disabled_roles.mcfunction"

if (-not (Test-Path -LiteralPath $ConfigPath)) {
    throw "Missing role source table: $ConfigPath"
}

$config = Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json
$roles = @($config.roles | ForEach-Object { [string] $_ } | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Sort-Object -Unique)
if ($roles.Count -eq 0) {
    throw "Role source table has no roles."
}

. $RoleCatalogHelper
$roleCatalog = @(Get-SybillianRoleCatalog -SetFromMenuPath $SetFromMenuPath -CharactersPath $CharactersPath -ExtensionPath $RoleExtensionPath)
$disabledRoleReasons = Get-BotcDisabledRoleMap -ContractPath $ContractPath -RoleCatalog $roleCatalog
$roleByName = @{}
foreach ($role in $roleCatalog) {
    $roleByName[[string] $role.Role] = $role
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("# Generated by tools/generate-setup-role-clear.ps1 from Jays-Patch/role-icons.json.")
$lines.Add("# Do not hand-edit this file; update the source table and regenerate.")
$lines.Add("# Reset only known BOTC role holders instead of every scoreboard holder.")

foreach ($role in $roles) {
    if ($role -notmatch '^[a-z0-9_]+$') {
        throw "Invalid role id in role source table: $role"
    }

    $lines.Add("scoreboard players reset $role role_list")
}

$outputDir = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($OutputPath, ($lines -join "`n") + "`n", $utf8NoBom)

New-Item -ItemType Directory -Path $CompatibilityRoot -Force | Out-Null
$requestLines = [System.Collections.Generic.List[string]]::new()
$requestLines.Add("# Generated by tools/generate-setup-role-clear.ps1 from Jays-Patch/upstream-contract.json.")
$requestLines.Add("# Reject compatibility-disabled direct setup requests.")
$requestLines.Add("scoreboard players set setup_role_allowed botc_patch 1")
foreach ($roleName in $disabledRoleReasons.Keys | Sort-Object) {
    $reason = ([string] $disabledRoleReasons[$roleName]).Replace("\", "\\").Replace('"', '\"')
    $displayName = ([string] $roleByName[$roleName].Name).Replace("\", "\\").Replace('"', '\"')
    $requestLines.Add(('execute if data storage botc_patch:setup compatibility{{role_request:"{0}"}} run scoreboard players set setup_role_allowed botc_patch 0' -f $roleName))
    $requestLines.Add(('execute if data storage botc_patch:setup compatibility{{role_request:"{0}"}} run tellraw @s [{{"text":"! ","color":"red","bold":true}},{{"text":"{1} is unavailable: {2}","color":"gray","bold":false}}]' -f $roleName, $displayName, $reason))
}
[System.IO.File]::WriteAllText((Join-Path $CompatibilityRoot "validate_role_request.mcfunction"), ($requestLines -join "`n") + "`n", $utf8NoBom)

$importLines = [System.Collections.Generic.List[string]]::new()
$importLines.Add("# Generated by tools/generate-setup-role-clear.ps1 from Jays-Patch/upstream-contract.json.")
$importLines.Add("# Reject scripts containing compatibility-disabled roles.")
foreach ($roleName in $disabledRoleReasons.Keys | Sort-Object) {
    $role = $roleByName[$roleName]
    $functionName = "fail_disabled_$roleName"
    $importLines.Add(('execute if data storage ct:script in_characters{{{0}:["{1}"]}} run function botc_patch:setup/import/{2}' -f [string] $role.StorageCategory, $roleName, $functionName))

    $reason = ([string] $disabledRoleReasons[$roleName]).Replace("\", "\\").Replace('"', '\"')
    $displayName = ([string] $role.Name).Replace("\", "\\").Replace('"', '\"')
    $failureLines = @(
        "# Generated by tools/generate-setup-role-clear.ps1 from Jays-Patch/upstream-contract.json.",
        "scoreboard players set setup_import_valid botc_patch 0",
        ('tellraw @s [{{"text":"! ","color":"red","bold":true}},{{"text":"Couldn''t import that script: {0} is unavailable. {1}","color":"gray","bold":false}}]' -f $displayName, $reason)
    )
    [System.IO.File]::WriteAllText((Join-Path $PatchRoot "datapack/data/botc_patch/function/setup/import/$functionName.mcfunction"), ($failureLines -join "`n") + "`n", $utf8NoBom)
}
[System.IO.File]::WriteAllText($ImportValidationPath, ($importLines -join "`n") + "`n", $utf8NoBom)

Write-Host ("Generated setup role cleanup for {0} roles and {1} compatibility exclusion(s)." -f $roles.Count, $disabledRoleReasons.Count)

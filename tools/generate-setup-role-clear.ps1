Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$PatchRoot = Join-Path $RepoRoot "Jays-Patch"
$ConfigPath = Join-Path $PatchRoot "role-icons.json"
$OutputPath = Join-Path $PatchRoot "datapack/data/botc_patch/function/setup/clear_known_roles.mcfunction"

if (-not (Test-Path -LiteralPath $ConfigPath)) {
    throw "Missing role source table: $ConfigPath"
}

$config = Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json
$roles = @($config.roles | ForEach-Object { [string] $_ } | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Sort-Object -Unique)
if ($roles.Count -eq 0) {
    throw "Role source table has no roles."
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("# Generated by tools/generate-setup-role-clear.ps1 from Jays-Patch/role-icons.json.")
$lines.Add("# Do not hand-edit this file; update the source table and regenerate.")
$lines.Add("# Reset only known BOTC role holders instead of every scoreboard holder.")

foreach ($role in $roles) {
    if ($role -notmatch '^[a-z0-9_]+$') {
        throw "Invalid role id in role source table: $role"
    }

    $lines.Add("scoreboard players reset $role role_list")
}

$outputDir = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($OutputPath, ($lines -join "`n") + "`n", $utf8NoBom)

Write-Host ("Generated setup role cleanup for {0} roles." -f $roles.Count)

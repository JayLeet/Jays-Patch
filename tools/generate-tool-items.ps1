function Read-JsonFile {
    param([string] $Path)

    try {
        return Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json
    }
    catch {
        throw "Invalid JSON in $Path`: $($_.Exception.Message)"
    }
}

function Assert-Property {
    param(
        [object] $Object,
        [string] $Name,
        [string] $Description
    )

    if (-not $Object.PSObject.Properties[$Name]) {
        throw "Missing $Description property '$Name'."
    }

    $value = [string] $Object.$Name
    if ([string]::IsNullOrWhiteSpace($value)) {
        throw "Empty $Description property '$Name'."
    }
}

function New-GeneratedHeader {
    param([string] $Description)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-tool-items.ps1 from Jays-Patch/tool-items.json.")
    $lines.Add("# Do not hand-edit this file; update the registry and regenerate.")
    $lines.Add("# $Description")
    return ,$lines
}

function New-ItemStack {
    param(
        [object] $Item,
        [string] $CustomDataMarker,
        [string] $CustomNameComponent,
        [string] $LoreComponent = "",
        [string] $ModelString = ""
    )

    $components = [System.Collections.Generic.List[string]]::new()
    $effectiveModelString = if ([string]::IsNullOrWhiteSpace($ModelString)) { [string] $Item.modelString } else { $ModelString }
    $components.Add(('minecraft:custom_model_data={{strings:["{0}"]}}' -f $effectiveModelString))
    $components.Add(('minecraft:custom_data={{{0}}}' -f $CustomDataMarker))
    $components.Add(('custom_name={0}' -f $CustomNameComponent))
    if (-not [string]::IsNullOrWhiteSpace($LoreComponent)) {
        $components.Add(('lore={0}' -f $LoreComponent))
    }

    return '{0}[{1}]' -f [string] $Item.item, ($components -join ",")
}

function New-ClearStack {
    param([object] $Item)

    return '{0}[minecraft:custom_model_data={{strings:["{1}"]}}]' -f `
        [string] $Item.item,
        [string] $Item.modelString
}

function New-StackSelector {
    param(
        [object] $Item,
        [object] $Row = $null
    )

    if ($null -ne $Row -and $Row.PSObject.Properties["customDataMarker"]) {
        return '{0}[minecraft:custom_data={{{1}}}]' -f [string] $Item.item, [string] $Row.customDataMarker
    }

    return New-ClearStack -Item $Item
}

function New-InventoryComponentPredicate {
    param(
        [object] $Item,
        [object] $Row
    )

    $slot = [string] $Row.slot
    if ($slot -notmatch '^hotbar\.([0-8])$') {
        throw "Expected hotbar slot for '$($Item.id)', got '$slot'."
    }

    $slotByte = "$($Matches[1])b"
    if ($Row.PSObject.Properties["customDataMarker"]) {
        return 'Inventory[{Slot:' + $slotByte + '}].components."minecraft:custom_data"{' + [string] $Row.customDataMarker + '}'
    }

    return 'Inventory[{Slot:' + $slotByte + '}].components."minecraft:custom_model_data"{strings:["' + [string] $Item.modelString + '"]}'
}

function New-SelectorFromEntityCondition {
    param(
        [string] $Condition,
        [string] $Description
    )

    if ($Condition -notmatch '^entity @s(?<suffix>\[.*\])?$') {
        throw "$Description must use an 'entity @s[...]' condition so item-check selectors can be generated, got '$Condition'."
    }

    return '@a' + [string] $Matches.suffix
}

function Get-ToolMode {
    param(
        [object] $Row,
        [string] $Description
    )

    $mode = "both"
    if ($Row.PSObject.Properties["mode"] -and -not [string]::IsNullOrWhiteSpace([string] $Row.mode)) {
        $mode = [string] $Row.mode
    }

    if ($mode -notin @("item", "dialog", "both")) {
        throw "$Description has unsupported mode '$mode'. Use item, dialog, or both."
    }

    return $mode
}

function Get-ModeConditionFragment {
    param(
        [object] $Row,
        [string] $Description,
        [switch] $Inverse
    )

    $mode = Get-ToolMode -Row $Row -Description $Description
    if ($mode -eq "both") {
        return ""
    }

    $keyword = if ($mode -eq "dialog") { "if" } else { "unless" }
    if ($Inverse) {
        $keyword = if ($keyword -eq "if") { "unless" } else { "if" }
    }

    return "$keyword score patch_dialog_mode botc_patch matches 1"
}

function Add-ModeCondition {
    param(
        [string] $Condition,
        [object] $Row,
        [string] $Description
    )

    $modeCondition = Get-ModeConditionFragment -Row $Row -Description $Description
    if ([string]::IsNullOrWhiteSpace($modeCondition)) {
        return $Condition
    }

    return "$Condition $modeCondition"
}

function Add-RepairCheckLines {
    param(
        [System.Collections.Generic.List[string]] $Lines,
        [string] $PhaseCondition,
        [string] $PlayerSelector,
        [object] $Entry,
        [string] $ScoreName = "botc_storyteller_items",
        [string] $RepairTag = "botc_st_tool_repair"
    )

    $description = "tool item '$($Entry.Item.id)'"
    $effectivePhaseCondition = Add-ModeCondition -Condition $PhaseCondition -Row $Entry.Row -Description $description
    $selector = New-StackSelector -Item $Entry.Item -Row $Entry.Row
    $inventoryPredicate = New-InventoryComponentPredicate -Item $Entry.Item -Row $Entry.Row
    $Lines.Add(('execute if {0} as {1} store result score @s {2} run clear @s {3} 0' -f `
        $effectivePhaseCondition,
        $PlayerSelector,
        $ScoreName,
        $selector))
    $Lines.Add(('execute if {0} as {1} unless score @s {2} matches 1 run tag @s add {3}' -f `
        $effectivePhaseCondition,
        $PlayerSelector,
        $ScoreName,
        $RepairTag))
    $Lines.Add(('execute if {0} as {1} unless data entity @s {2} run tag @s add {3}' -f `
        $effectivePhaseCondition,
        $PlayerSelector,
        $inventoryPredicate,
        $RepairTag))
}

function Get-LiveToolRowsForPhaseGroup {
    param([string] $Group)

    $conditions = switch ($Group) {
        "day" { @("score phase game_data matches 1..2", "score phase game_data matches 1..3") }
        "nomination" { @("score phase game_data matches 3", "score phase game_data matches 1..3") }
        "night" { @("score phase game_data matches 4") }
        "night_house" { @() }
        default { throw "Unsupported live tool phase group '$Group'." }
    }

    return @(
        $liveToolRows |
            Where-Object {
                if ([string] $_.Item.id -eq "grim_reveal_menu") {
                    $false
                }
                else {
                    $repairGroup = if ($_.Row.PSObject.Properties["repairGroup"]) {
                        [string] $_.Row.repairGroup
                    }
                    else {
                        ""
                    }

                    if ($Group -eq "night_house") {
                        $repairGroup -eq "night_house"
                    }
                    elseif (-not [string]::IsNullOrWhiteSpace($repairGroup)) {
                        $false
                    }
                    else {
                        ([string] $_.Row.condition) -in $conditions
                    }
                }
            } |
            Sort-Object { [int] $_.Row.order }
    )
}

function Write-OrCheckFile {
    param(
        [string] $Path,
        [System.Collections.Generic.List[string]] $Lines
    )

    $content = ($Lines -join "`n") + "`n"
    if ($Check) {
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
            throw "Generated file is missing: $Path"
        }

        $existing = Get-Content -LiteralPath $Path -Raw
        if ($existing -ne $content) {
            throw "Generated file is stale: $Path. Run tools/generate-tool-items.ps1."
        }

        return
    }

    $dir = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $dir -PathType Container)) {
        New-Item -ItemType Directory -Path $dir | Out-Null
    }

    [System.IO.File]::WriteAllText($Path, $content, $Utf8NoBom)
    Write-Host "Generated $Path"
}


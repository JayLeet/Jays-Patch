Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$MusicTrackPath = Join-Path $RepoRoot "Jays-Patch/music-tracks.json"
$DialogIconPath = Join-Path $RepoRoot "Jays-Patch/dialog-icons.json"
$DialogIconHelper = Join-Path $RepoRoot "tools/lib/dialog-icons.ps1"
$OutputRoot = Join-Path $RepoRoot "Jays-Patch/datapack/data/botc_patch/function/music"
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)

. $DialogIconHelper
$music = Get-Content -LiteralPath $MusicTrackPath -Raw -Encoding UTF8 | ConvertFrom-Json
$tracks = @($music.tracks)
$icons = Get-BotcDialogIconCatalog -DialogIconPath $DialogIconPath -MusicTrackPath $MusicTrackPath

function Write-Lines {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [System.Collections.Generic.List[string]] $Lines
    )

    [System.IO.File]::WriteAllText($Path, (($Lines -join "`n") + "`n"), $utf8NoBom)
}

function New-Header {
    param([Parameter(Mandatory)] [string] $Responsibility)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-music.ps1.")
    $lines.Add("# Do not hand-edit this file; update Jays-Patch/music-tracks.json and regenerate.")
    $lines.Add("# $Responsibility")
    return ,$lines
}

$trackIds = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
$pickIds = [System.Collections.Generic.HashSet[int]]::new()
$triggerIds = [System.Collections.Generic.HashSet[int]]::new()
$menuOrders = [System.Collections.Generic.HashSet[int]]::new()
foreach ($track in $tracks) {
    if (-not $trackIds.Add([string] $track.id)) { throw "Duplicate music track id '$($track.id)'." }
    if (-not $pickIds.Add([int] $track.pick)) { throw "Duplicate music pick '$($track.pick)'." }
    if (-not $triggerIds.Add([int] $track.trigger)) { throw "Duplicate music trigger '$($track.trigger)'." }
    if (-not $menuOrders.Add([int] $track.menuOrder)) { throw "Duplicate music menu order '$($track.menuOrder)'." }
    if ([int] $track.trigger -eq [int] $music.togglePitchTrigger) { throw "Music track '$($track.id)' uses reserved Toggle Pitch trigger $($music.togglePitchTrigger)." }
    if ([string] $track.playbackMode -notin @("disc", "ambient")) { throw "Music track '$($track.id)' has invalid playback mode '$($track.playbackMode)'." }
}

$expectedPicks = @(0..($tracks.Count - 1))
$actualPicks = @($tracks | Sort-Object { [int] $_.pick } | ForEach-Object { [int] $_.pick })
if (($expectedPicks -join ',') -ne ($actualPicks -join ',')) {
    throw "Music picks must be contiguous from 0 through $($tracks.Count - 1)."
}

$menuActions = [System.Collections.Generic.List[string]]::new()
$menuActions.Add('{label:' + (New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "music") -Font "botc_patch:ui_icons" -Text "Resume Current" -Color "green" -Bold $true) + ',action:{type:"run_command",command:"/trigger botc_music_select set 2"}}')
$menuActions.Add('{label:' + (New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "random") -Font "botc_patch:ui_icons" -Text "Random Track" -Color "gold" -Bold $true) + ',action:{type:"run_command",command:"/trigger botc_music_select set 3"}}')
$menuActions.Add('{label:' + (New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "pitch") -Font "botc_patch:ui_icons" -Text "Toggle Pitch" -Color "aqua" -Bold $true) + ',action:{type:"run_command",command:"/trigger botc_music_select set ' + [int] $music.togglePitchTrigger + '"}}')
$menuActions.Add('{label:' + (New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "off") -Font "botc_patch:ui_icons" -Text "Turn Off" -Color "dark_red" -Bold $true) + ',action:{type:"run_command",command:"/trigger botc_music_select set 1"}}')
foreach ($track in @($tracks | Sort-Object { [int] $_.menuOrder })) {
    $label = New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "music_$($track.id)") -Font "botc_patch:ui_icons" -Text ([string] $track.label) -Color "white"
    $menuActions.Add('{label:' + $label + ',action:{type:"run_command",command:"/trigger botc_music_select set ' + [int] $track.trigger + '"}}')
}

$menuLines = New-Header "Shows four music controls followed by every 1.21.10 jukebox disc and retained ambient track."
$title = New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id "music") -Font "botc_patch:ui_icons" -Text "Night Music" -Color "white"
$menuLines.Add('dialog show @s {type:"multi_action",title:' + $title + ',columns:4,actions:[' + ($menuActions -join ',') + ']}')
Write-Lines -Path (Join-Path $OutputRoot "menu.mcfunction") -Lines $menuLines

$selectLines = New-Header "Routes stable trigger values into music controls or a selected track."
$selectLines.Add('execute unless score phase game_data matches 4 run tellraw @s [{text:"You can only change night music at night.",color:"gray"}]')
$selectLines.Add('execute unless score phase game_data matches 4 run return 0')
$selectLines.Add('')
$selectLines.Add('execute if score @s botc_music_select matches 1 run function botc_patch:music/off')
$selectLines.Add('execute if score @s botc_music_select matches 2 run function botc_patch:music/on')
$selectLines.Add('execute if score @s botc_music_select matches 3 run function botc_patch:music/random_self')
foreach ($track in @($tracks | Sort-Object { [int] $_.trigger })) {
    $selectLines.Add("execute if score @s botc_music_select matches $([int] $track.trigger) run scoreboard players set @s botc_music_pick $([int] $track.pick)")
}
$selectLines.Add("execute if score @s botc_music_select matches $([int] $music.togglePitchTrigger) run function botc_patch:music/toggle_pitch")
foreach ($track in @($tracks | Sort-Object { [int] $_.trigger })) {
    $selectLines.Add("execute if score @s botc_music_select matches $([int] $track.trigger) run function botc_patch:music/play_selected")
}
Write-Lines -Path (Join-Path $OutputRoot "select.mcfunction") -Lines $selectLines

$playLines = New-Header "Plays one selected track with the established low randomized disc variants or native ambient settings."
$playLines.Add('tag @s remove botc_music_off')
$playLines.Add('tag @s add botc_music_manual_selected')
$playLines.Add('tag @s add botc_music_target')
$playLines.Add('stopsound @s record')
$playLines.Add('stopsound @s music')
$playLines.Add('execute store result score @s botc_music_variant run random value 0..5')
$discVolumes = @(0.20, 0.22, 0.24, 0.26, 0.28, 0.30)
$discPitches = @(0.42, 0.45, 0.48, 0.52, 0.56, 0.60)
foreach ($track in @($tracks | Sort-Object { [int] $_.pick })) {
    for ($variant = 0; $variant -le 5; $variant++) {
        if ([string] $track.playbackMode -eq "disc") {
            $volume = $discVolumes[$variant].ToString('0.00', [Globalization.CultureInfo]::InvariantCulture)
            $pitch = $discPitches[$variant].ToString('0.00', [Globalization.CultureInfo]::InvariantCulture)
        }
        else {
            $volume = "1.0"
            $pitch = "1.0"
        }
        $playLines.Add('execute if score @s botc_music_pick matches ' + [int] $track.pick + ' if score @s botc_music_variant matches ' + $variant + ' run function botc_patch:music/play_to_selected {sound:"' + [string] $track.sound + '",volume:' + $volume + ',pitch:' + $pitch + '}')
    }
}
$playLines.Add('tag @s remove botc_music_target')
$playLines.Add('tellraw @s [{text:"Night music changed.",color:"aqua"}]')
Write-Lines -Path (Join-Path $OutputRoot "play_selected.mcfunction") -Lines $playLines

$randomLines = New-Header "Chooses uniformly from every track exposed in the Night Music dialog."
$randomLines.Add("execute store result score @s botc_music_pick run random value 0..$($tracks.Count - 1)")
$randomLines.Add('function botc_patch:music/play_selected')
Write-Lines -Path (Join-Path $OutputRoot "random_self.mcfunction") -Lines $randomLines

Write-Host "Generated Night Music menu and playback for $($tracks.Count) tracks." -ForegroundColor Green

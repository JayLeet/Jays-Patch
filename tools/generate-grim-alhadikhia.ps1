$dispatchLines.Add('function botc_patch:grim/editor/player_labels/prepare')
for ($seatCount = 0; $seatCount -le 15; $seatCount++) {
    $dispatchLines.Add("execute if score grim_editor_dialog_size botc_patch matches $seatCount run function botc_patch:grim/alhadikhia/player_dialog/count_$seatCount with storage botc_patch:grim editor.player_labels")

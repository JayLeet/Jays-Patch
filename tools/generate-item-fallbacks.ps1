Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$PatchRoot = Join-Path $RepoRoot "Jays-Patch"
$ConfigPath = Join-Path $PatchRoot "item-fallbacks.json"

function Get-MinecraftSlotName {
    param([int] $Slot)

    if ($Slot -ge 0 -and $Slot -le 8) {
        return "hotbar.$Slot"
    }

    if ($Slot -ge 9 -and $Slot -le 35) {
        return "inventory.$($Slot - 9)"
    }

    throw "Unsupported inventory slot in fallback table: $Slot"
}

function New-HashSet {
    param([int[]] $Values)

    $set = [System.Collections.Generic.HashSet[int]]::new()
    foreach ($value in $Values) {
        [void] $set.Add($value)
    }
    return ,$set
}

if (-not (Test-Path -LiteralPath $ConfigPath)) {
    throw "Missing item fallback source table: $ConfigPath"
}

$config = Get-Content -LiteralPath $ConfigPath -Raw | ConvertFrom-Json
$slotOrder = @($config.slotOrder | ForEach-Object { [int] $_ })

foreach ($entry in @($config.items)) {
    $outputPath = Join-Path $PatchRoot ([string] $entry.output)
    $outputDir = Split-Path -Parent $outputPath
    if (-not (Test-Path -LiteralPath $outputDir)) {
        New-Item -ItemType Directory -Path $outputDir | Out-Null
    }

    $skipSlots = New-HashSet @($entry.skipSlots | ForEach-Object { [int] $_ })
    $item = [string] $entry.item
    $customModelData = [string] $entry.customModelData
    $score = [string] $entry.score
    $customName = [string] $entry.customNameComponent

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-item-fallbacks.ps1 from Jays-Patch/item-fallbacks.json.")
    $lines.Add("# Do not hand-edit this file; update the source table and regenerate.")
    $lines.Add("# $($entry.description)")

    $entrySlotOrder = $slotOrder
    if ($entry.PSObject.Properties.Name -contains "slotOrder") {
        $entrySlotOrder = @($entry.slotOrder | ForEach-Object { [int] $_ })
    }

    foreach ($slot in $entrySlotOrder) {
        if ($skipSlots.Contains($slot)) {
            continue
        }

        $minecraftSlot = Get-MinecraftSlotName $slot
        $itemStack = '{0}[minecraft:custom_model_data={{strings:["{1}"]}},minecraft:custom_data={{botc_patch_tool:1b}},custom_name={2}]' -f $item, $customModelData, $customName
        $clearItem = '{0}[minecraft:custom_model_data={{strings:["{1}"]}}]' -f $item, $customModelData
        $lines.Add(('execute store result score @s {0} run clear @s {1} 0' -f $score, $clearItem))
        $lines.Add(('execute if score @s {0} matches 0 unless data entity @s Inventory[{{Slot:{1}b}}] run item replace entity @s {2} with {3}' -f $score, $slot, $minecraftSlot, $itemStack))
    }

    $content = ($lines -join [Environment]::NewLine) + [Environment]::NewLine
    $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText($outputPath, $content, $utf8NoBom)
    Write-Host "Generated $outputPath"
}

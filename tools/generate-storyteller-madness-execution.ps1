Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$OutputRoot = Join-Path $RepoRoot "Jays-Patch/datapack/data/botc_patch/function/storyteller_tools/madness_execution"

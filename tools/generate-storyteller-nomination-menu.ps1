function New-GeneratedHeader {
    param([string] $Responsibility)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-storyteller-nomination-menu.ps1.")
    $lines.Add("# Do not hand-edit this file; update the generator and regenerate.")
    $lines.Add("# $Responsibility")
    return ,$lines
}

function Write-Lines {
    param(
        [string] $Path,
        [System.Collections.Generic.List[string]] $Lines
    )

    [System.IO.File]::WriteAllText($Path, (($Lines -join "`n") + "`n"), $utf8NoBom)
}

function Write-JsonFile {
    param([string] $Path, [object] $Value)
    $json = ($Value | ConvertTo-Json -Depth 100).Replace("`r`n", "`n")
    [System.IO.File]::WriteAllText($Path, ($json + "`n"), $utf8NoBom)
}

function Write-SolidColorPng {
    param([string] $Path, [string] $Hex)

    Add-Type -AssemblyName System.Drawing
    $bitmap = [System.Drawing.Bitmap]::new(16, 16)
    $color = [System.Drawing.ColorTranslator]::FromHtml($Hex)
    for ($x = 0; $x -lt 16; $x++) {
        for ($y = 0; $y -lt 16; $y++) {
            $bitmap.SetPixel($x, $y, $color)
        }
    }
    try {
        $bitmap.Save($Path, [System.Drawing.Imaging.ImageFormat]::Png)
    }
    finally {
        $bitmap.Dispose()
    }
}


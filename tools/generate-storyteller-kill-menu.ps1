Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$OutputRoot = Join-Path $RepoRoot "Jays-Patch\datapack\data\botc_patch\function\storyteller_tools\kill_menu"
$ToolRegistryLib = Join-Path $PSScriptRoot "lib\tool-registry.ps1"
$PlayerDialogLib = Join-Path $PSScriptRoot "lib\player-dialog-generator.ps1"

foreach ($library in @($ToolRegistryLib, $PlayerDialogLib)) {
    if (-not (Test-Path -LiteralPath $library -PathType Leaf)) {
        throw "Missing generator helper: $library"
    }
    . $library
}

$toolRegistryContext = Read-BotcToolRegistry -RepoRoot $RepoRoot
$seatColorNames = @(
    "red", "orange", "yellow", "lime", "green",
    "mint", "cyan", "blue", "navy", "purple",
    "magenta", "lavender", "white", "gray", "black"
)
$legacyActionModels = @("storyteller_kill_back", "storyteller_kill_next") | ForEach-Object {
    New-BotcResourceCaseModel -Tool (Get-BotcToolItem -Context $toolRegistryContext -Id $_)
}

$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
New-Item -ItemType Directory -Path $OutputRoot -Force | Out-Null

function New-GeneratedHeader {
    param([string] $Responsibility)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-storyteller-kill-menu.ps1.")
    $lines.Add("# Do not hand-edit this file; update the generator and regenerate.")
    $lines.Add("# $Responsibility")
    return ,$lines
}

function Write-Lines {
    param(
        [string] $Path,
        [System.Collections.Generic.List[string]] $Lines
    )

    [System.IO.File]::WriteAllText($Path, (($Lines -join [Environment]::NewLine) + [Environment]::NewLine), $utf8NoBom)
}

$open = New-GeneratedHeader "Opens the filtered alive-player Kill dialog without replacing the Storyteller hotbar."
$open.Add("tag @s add botc_st_tool_used")
$open.Add("execute unless entity @s[tag=storyteller] run return 0")
$open.Add('execute unless score phase game_data matches 1..2 run return run tellraw @s [{text:"Kill is only available during live day phases.",color:"red"}]')
$open.Add("function botc_patch:storyteller_tools/kill_menu/dialog")
Write-Lines -Path (Join-Path $OutputRoot "open.mcfunction") -Lines $open

Write-BotcFilteredPlayerDialog `
    -OutputRoot $OutputRoot `
    -FunctionPath "storyteller_tools/kill_menu" `
    -GeneratorName "tools/generate-storyteller-kill-menu.ps1" `
    -StorageKey "kill" `
    -Title "Kill Player" `
    -BodyText "Choose an alive seated player." `
    -EligibilitySelectorTemplate '@a[tag=!storyteller,tag=!spectator,tag=!dead,scores={id=<seat>},limit=1]' `
    -ActionCommand "kill_player" `
    -PhaseCondition "score phase game_data matches 1..2" `
    -InvalidPhaseMessage "Kill is only available during live day phases." `
    -NoPlayersMessage "No alive seated players are available to kill."

$selectPlayer = New-GeneratedHeader "Validates a dialog seat before dispatching to its fixed Kill function."
$selectPlayer.Add("dialog clear @s")
$selectPlayer.Add("execute unless entity @s[tag=storyteller] run return 0")
$selectPlayer.Add('execute unless score phase game_data matches 1..2 run return run tellraw @s [{text:"Kill is only available during live day phases.",color:"red"}]')
$selectPlayer.Add('$function botc_patch:storyteller_tools/kill_menu/to_seat_$(seat)')
Write-Lines -Path (Join-Path $OutputRoot "select_player.mcfunction") -Lines $selectPlayer

for ($seat = 1; $seat -le 15; $seat++) {
    $targetSelector = "@a[tag=!storyteller,tag=!spectator,tag=!dead,scores={id=$seat},limit=1]"
    $lines = New-GeneratedHeader "Kills the currently alive player in seat $seat through Sybillian."
    $lines.Add("tag @s add botc_st_tool_used")
    $lines.Add("dialog clear @s")
    $lines.Add(('execute unless entity {0} run return run tellraw @s [{{text:"That player is not available to kill.",color:"red"}}]' -f $targetSelector))
    $lines.Add("execute as $targetSelector run function ct:kill/die")
    Write-Lines -Path (Join-Path $OutputRoot "to_seat_$seat.mcfunction") -Lines $lines
}

$close = New-GeneratedHeader "Cleans an interrupted legacy hotbar picker and restores normal Storyteller tools."
$close.Add("dialog clear @s")
$close.Add("tag @s add botc_st_tool_used")
$close.Add("tag @s remove botc_st_kill_menu")
$close.Add("tag @s remove botc_st_kill_was_page_2")
$close.Add("scoreboard players reset @s botc_st_kill_page")
$close.Add("scoreboard players reset @s botc_st_menu_slot")
$close.Add("function botc_patch:storyteller_tools/kill_menu/clear_items")
$close.Add("function botc_patch:storyteller_tools/replace_items")
Write-Lines -Path (Join-Path $OutputRoot "close.mcfunction") -Lines $close

$clearItems = New-GeneratedHeader "Clears retired Kill hotbar-picker items from the current Storyteller."
foreach ($item in $legacyActionModels) {
    $clearItems.Add(('clear @s minecraft:carrot_on_a_stick[minecraft:custom_model_data={{strings:["{0}"]}}]' -f $item.String))
}
foreach ($color in $seatColorNames) {
    $clearItems.Add(('clear @s minecraft:carrot_on_a_stick[minecraft:custom_model_data={{strings:["storyteller_kill_{0}"]}}]' -f $color))
    $clearItems.Add(('clear @s minecraft:carrot_on_a_stick[minecraft:custom_model_data={{strings:["storyteller_nom_{0}"]}}]' -f $color))
}
$clearItems.Add("function botc_patch:storyteller_tools/player_menu/clear_role_items")
Write-Lines -Path (Join-Path $OutputRoot "clear_items.mcfunction") -Lines $clearItems

$cleanup = New-GeneratedHeader "Removes retired Kill picker state left by an older deployment."
foreach ($item in $legacyActionModels) {
    $cleanup.Add(('clear @a minecraft:carrot_on_a_stick[minecraft:custom_model_data={{strings:["{0}"]}}]' -f $item.String))
}
foreach ($color in $seatColorNames) {
    $cleanup.Add(('clear @a minecraft:carrot_on_a_stick[minecraft:custom_model_data={{strings:["storyteller_kill_{0}"]}}]' -f $color))
}
$cleanup.Add("tag @a remove botc_st_kill_menu")
$cleanup.Add("tag @a remove botc_st_kill_was_page_2")
$cleanup.Add("tag @a remove botc_st_kill_done")
$cleanup.Add("scoreboard players reset @a botc_st_kill_page")
Write-Lines -Path (Join-Path $OutputRoot "cleanup_items.mcfunction") -Lines $cleanup

foreach ($staleName in @("back.mcfunction", "page_1.mcfunction", "page_2.mcfunction")) {
    Remove-Item -LiteralPath (Join-Path $OutputRoot $staleName) -Force -ErrorAction SilentlyContinue
}

Write-Host "Generated Storyteller Kill dialog with filtered Player (Role) labels."

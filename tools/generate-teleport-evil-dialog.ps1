Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$OutputRoot = Join-Path $RepoRoot "Jays-Patch/datapack/data/botc_patch/function/storyteller_tools"
$DialogIconPath = Join-Path $RepoRoot "Jays-Patch/dialog-icons.json"
$MusicTrackPath = Join-Path $RepoRoot "Jays-Patch/music-tracks.json"
$DialogIconHelper = Join-Path $RepoRoot "tools/lib/dialog-icons.ps1"
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)

. $DialogIconHelper
$icons = Get-BotcDialogIconCatalog -DialogIconPath $DialogIconPath -MusicTrackPath $MusicTrackPath

function Write-Lines {
    param(
        [Parameter(Mandatory)] [string] $Path,
        [Parameter(Mandatory)] [System.Collections.Generic.List[string]] $Lines
    )

    New-Item -ItemType Directory -Path (Split-Path -Parent $Path) -Force | Out-Null
    [System.IO.File]::WriteAllText($Path, (($Lines -join "`n") + "`n"), $utf8NoBom)
}

function New-Header {
    param([Parameter(Mandatory)] [string] $Responsibility)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add("# Generated by tools/generate-teleport-evil-dialog.ps1.")
    $lines.Add("# Do not hand-edit this file; update the generator and regenerate.")
    $lines.Add("# $Responsibility")
    return ,$lines
}

function New-RoleGlyphComponents {
    param([Parameter(Mandatory)] [string] $Prefix)

    $components = [System.Collections.Generic.List[string]]::new()
    for ($index = 1; $index -le 15; $index++) {
        $components.Add('{text:"$(' + $Prefix + $index + '_glyph)",font:"botc_patch:role_icons",color:"white"}')
    }
    return ,$components
}

$entryLines = New-Header "Builds private in-play Demon and Minion role-icon rows before showing teleport choices."
$entryLines.Add('tag @s add botc_st_tool_used')
$entryLines.Add('dialog clear @s')
$entryLines.Add('execute unless entity @s[tag=storyteller] run return 0')
$entryLines.Add('execute unless score phase game_data matches 4 run return run tellraw @s [{text:"! ",color:"red",bold:true},{text:"You can only teleport the evil team at night.",color:"gray",bold:false}]')
$entryLines.Add('function botc_patch:grim/editor/refresh_live_roles')
$entryLines.Add('function botc_patch:grim/editor/player_labels/prepare')
$entryLines.Add('data remove storage botc_patch:dialogs teleport_evil')
$entryLines.Add('scoreboard players set #tp_evil_demons botc_patch 0')
$entryLines.Add('scoreboard players set #tp_evil_minions botc_patch 0')
foreach ($group in @('demon', 'minion')) {
    for ($index = 1; $index -le 15; $index++) {
        $entryLines.Add("data modify storage botc_patch:dialogs teleport_evil.$group$($index)_glyph set value `"`"")
    }
}
for ($seat = 1; $seat -le 15; $seat++) {
    foreach ($group in @('demon', 'minion')) {
        $counter = if ($group -eq 'demon') { '#tp_evil_demons' } else { '#tp_evil_minions' }
        $selector = "@a[tag=$group,tag=!storyteller,tag=!spectator,scores={id=$seat,role=1..}]"
        $entryLines.Add("execute if entity $selector run scoreboard players add $counter botc_patch 1")
        $entryLines.Add("execute if entity $selector run data modify storage botc_patch:dialogs teleport_evil_lookup set value {group:`"$group`",source:$seat,target:0}")
        $entryLines.Add("execute if entity $selector store result storage botc_patch:dialogs teleport_evil_lookup.target int 1 run scoreboard players get $counter botc_patch")
        $entryLines.Add("execute if entity $selector run function botc_patch:storyteller_tools/teleport_evil/append_icon with storage botc_patch:dialogs teleport_evil_lookup")
    }
}
$entryLines.Add('function botc_patch:storyteller_tools/teleport_evil/show with storage botc_patch:dialogs teleport_evil')
$entryLines.Add('scoreboard players reset #tp_evil_demons botc_patch')
$entryLines.Add('scoreboard players reset #tp_evil_minions botc_patch')
Write-Lines -Path (Join-Path $OutputRoot 'teleport_evil.mcfunction') -Lines $entryLines

$appendLines = New-Header "Copies one active evil player's current role glyph into its private team row."
$appendLines.Add('$data modify storage botc_patch:dialogs teleport_evil.$(group)$(target)_glyph set from storage botc_patch:grim editor.player_labels.p$(source)_glyph')
Write-Lines -Path (Join-Path $OutputRoot 'teleport_evil/append_icon.mcfunction') -Lines $appendLines

$demonComponents = New-RoleGlyphComponents -Prefix 'demon'
$minionComponents = New-RoleGlyphComponents -Prefix 'minion'
$demonLabel = @($demonComponents) + '{text:" Demon Only",font:"minecraft:default",color:"dark_red"}'
$minionLabel = @($minionComponents) + '{text:" Minions Only",font:"minecraft:default",color:"gold"}'
$bothLabel = @($demonComponents) + @($minionComponents) + '{text:" Demon + Minions",font:"minecraft:default",color:"red"}'
$title = New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id 'teleport_evil') -Font 'botc_patch:ui_icons' -Text 'Teleport Evil Team' -Color 'white'
$back = New-BotcDialogGlyphLabel -Glyph (Get-BotcDialogIconGlyph -Catalog $icons -Id 'back') -Font 'botc_patch:ui_icons' -Text 'Back' -Color 'gray'

$showLines = New-Header "Shows private evil-team choices with the actual in-play role icons."
$showLines.Add('$dialog show @s {type:"multi_action",title:' + $title + ',body:{type:"plain_message",contents:{text:"Pick who comes with you to the church.",color:"gray"},width:340},actions:[{label:[' + ($demonLabel -join ',') + '],action:{type:"run_command",command:"/botc teleport_evil demon"}},{label:[' + ($minionLabel -join ',') + '],action:{type:"run_command",command:"/botc teleport_evil minions"}},{label:[' + ($bothLabel -join ',') + '],action:{type:"run_command",command:"/botc teleport_evil both"}}],exit_action:{label:' + $back + ',action:{type:"run_command",command:"/botc dialog_cancel"}}}')
Write-Lines -Path (Join-Path $OutputRoot 'teleport_evil/show.mcfunction') -Lines $showLines

Write-Host "Generated private evil-team teleport dialog with current role icons." -ForegroundColor Green
